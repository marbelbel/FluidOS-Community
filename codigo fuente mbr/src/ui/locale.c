static int text_equal(const char *left, const char *right) {
    if (left == 0 || right == 0) return left == right;
    while (*left != '\0' && *right != '\0') {
        if (*left++ != *right++) return 0;
    }
    return *left == *right;
}

void locale_init(void) {
    active_language = VOS_LANGUAGE_SPANISH;
}

enum vos_language locale_current(void) {
    return active_language;
}

int locale_set(enum vos_language language) {
    if ((uint32_t)language >= (uint32_t)VOS_LANGUAGE_COUNT) return 0;
    active_language = language;
    return 1;
}

void locale_toggle(void) {
    active_language = active_language == VOS_LANGUAGE_SPANISH
        ? VOS_LANGUAGE_ENGLISH : VOS_LANGUAGE_SPANISH;
}

const char *locale_name(void) {
    return active_language == VOS_LANGUAGE_ENGLISH ? "English" : "Español";
}

const char *locale_translate(const char *spanish_text) {
    if (spanish_text == 0 || active_language == VOS_LANGUAGE_SPANISH) {
        return spanish_text;
    }
    for (uint32_t i = 0; i < sizeof(translations) / sizeof(translations[0]); i++) {
        if (text_equal(spanish_text, translations[i].spanish)) {
            return translations[i].english;
        }
    }
    return spanish_text;
}
